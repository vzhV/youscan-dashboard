from collections.abc import Iterator
from io import BytesIO
from xml.etree.ElementTree import ParseError
from zipfile import BadZipFile

from openpyxl import load_workbook
from openpyxl.utils.exceptions import InvalidFileException
from openpyxl.workbook.workbook import Workbook
from openpyxl.worksheet._read_only import ReadOnlyWorksheet

from app.core.errors import InvalidFileError
from app.importing.limits import ImportLimits, too_many_sheets
from app.importing.table import Table, build_table

# OSError: openpyxl reports a zip without a workbook part that way. ParseError: truncated or broken XML parts.
# ValueError/TypeError: unparsable cell values or coordinates raised while rows are streamed.
# AttributeError: openpyxl crashes while loading a chartsheet that has no chart (no relationships part);
# chartsheets that hold a chart load fine and are skipped, since they carry no rows.
_CORRUPT_WORKBOOK_ERRORS = (
    BadZipFile,
    KeyError,
    InvalidFileException,
    ParseError,
    OSError,
    ValueError,
    TypeError,
    AttributeError,
)


class XlsxParser:
    """Reads every non-empty sheet of an .xlsx workbook.

    Known limitation: cells are read with data_only=True, so a formula that has no cached value
    (a file generated by a library and never opened in Excel) reads as empty.
    """

    extensions = frozenset({".xlsx"})

    def parse(self, content: bytes, limits: ImportLimits) -> list[Table]:
        workbook = _open_workbook(content)
        try:
            if len(workbook.worksheets) > limits.max_sheets:
                raise too_many_sheets(limits.max_sheets, len(workbook.worksheets))
            tables = [
                build_table(sheet.title, _numbered_rows(sheet), limits) for sheet in workbook.worksheets
            ]
        finally:
            # read_only mode keeps the file handle open until closed.
            workbook.close()
        return [table for table in tables if table]


def _invalid_workbook() -> InvalidFileError:
    return InvalidFileError("File is not a valid .xlsx workbook")


def _open_workbook(content: bytes) -> Workbook:
    # Only openpyxl calls are wrapped, so a bug in our own code is never reported as a bad file.
    try:
        return load_workbook(BytesIO(content), read_only=True, data_only=True)
    except _CORRUPT_WORKBOOK_ERRORS as error:
        raise _invalid_workbook() from error


def _numbered_rows(sheet: ReadOnlyWorksheet) -> Iterator[tuple[int, tuple[object, ...]]]:
    # Dropping the declared dimension stops rows being padded to it (one stray cell at XFD
    # would otherwise widen every row to 16,384 values).
    sheet.reset_dimensions()
    try:
        # The types-openpyxl stub declares iter_rows for Worksheet only, though read-only sheets have it.
        rows = sheet.iter_rows(values_only=True)  # type: ignore[misc]
        yield from enumerate(rows, start=1)
    except _CORRUPT_WORKBOOK_ERRORS as error:
        raise _invalid_workbook() from error
